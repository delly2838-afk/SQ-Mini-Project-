--9.Which three products do people buy most at night (2020 - 2022)  
SELECT
    p.product_id,
    p.product_name,
    SUM(o.quantity) AS total_quantity_sold
FROM orders o
INNER JOIN products p
    ON o.product_id = p.product_id
WHERE (
        o.order_time >= TIME '20:00'
        OR o.order_time < TIME '06:00'
      )
  AND o.order_date >= DATE '2020-01-01'
  AND o.order_date < DATE '2023-01-01'
GROUP BY p.product_id, p.product_name
ORDER BY total_quantity_sold DESC
LIMIT 3;

--10.Is it true that 25% of our revenue is generated from juices?
WITH revenue_summary AS (
SELECT
    SUM(o.quantity * p.unit_price) AS total_revenue,
    SUM(
    CASE
    WHEN p.product_name ILIKE '%juice%'
    THEN o.quantity * p.unit_price
    ELSE 0
    END
   ) AS juice_revenue
   FROM orders o
   JOIN products p
   ON o.product_id = p.product_id
)
SELECT
    total_revenue,
    juice_revenue,
    ROUND(
     100.0 * juice_revenue / NULLIF(total_revenue, 0),
     2
   ) AS juice_revenue_percentage,
   CASE
   WHEN ABS(
   100.0 * juice_revenue / NULLIF(total_revenue, 0) - 25
   ) < 0.01
   THEN 'Yes'
   ELSE 'No'
   END AS is_juice_revenue_25_percent
FROM revenue_summary;






