--7.What time of day do we sell alcohol the most?
SELECT
    CASE
        WHEN o.order_time >= TIME '06:00'
         AND o.order_time < TIME '12:00' THEN 'Morning'
        WHEN o.order_time >= TIME '12:00'
         AND o.order_time < TIME '17:00' THEN 'Afternoon'
        WHEN o.order_time >= TIME '17:00'
         AND o.order_time < TIME '21:00' THEN 'Evening'
        ELSE 'Night'
    END AS time_of_day,
    SUM(o.quantity) AS total_alcohol_sold
FROM orders o
INNER JOIN products p
    ON o.product_id = p.product_id
INNER JOIN departments d
    ON p.dept_id = d.department_id
WHERE LOWER(d.department) = 'alcohol'
GROUP BY
    CASE
        WHEN o.order_time >= TIME '06:00'
         AND o.order_time < TIME '12:00' THEN 'Morning'
        WHEN o.order_time >= TIME '12:00'
         AND o.order_time < TIME '17:00' THEN 'Afternoon'
        WHEN o.order_time >= TIME '17:00'
         AND o.order_time < TIME '21:00' THEN 'Evening'
        ELSE 'Night'
    END
ORDER BY total_alcohol_sold DESC;

