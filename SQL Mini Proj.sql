--1.What are the top-selling products by revenue, and how much revenue have they generated?
   SELECT
    p.product_id,
    p.product_name,
    SUM(o.quantity * p.unit_price) AS total_revenue
FROM orders o
INNER JOIN products p
    ON o.product_id = p.product_id
GROUP BY
    p.product_id,
    p.product_name
ORDER BY total_revenue DESC
LIMIT 10;

--2.On which day of the week are chocolates mostly sold?
SELECT
    TRIM(TO_CHAR(o.order_date, 'Day')) AS day_of_week,
    SUM(o.quantity) AS total_chocolates_sold
FROM orders o
INNER JOIN products p
    ON o.product_id = p.product_id
WHERE p.product_name ILIKE '%chocolate%'
GROUP BY EXTRACT(ISODOW FROM o.order_date),
         TRIM(TO_CHAR(o.order_date, 'Day'))
ORDER BY total_chocolates_sold DESC;

/*3.Do we have any department that generated more than $15 million in revenue? 
If so, what was the profit generated by that department?*/
SELECT
    d.department,
    SUM(o.quantity * p.unit_price) AS total_revenue,
    SUM(o.quantity * (p.unit_price - p.unit_cost)) AS total_profit
FROM orders o
INNER JOIN products p
    ON o.product_id = p.product_id
INNER JOIN departments d
    ON p.dept_id = d.department_id
GROUP BY d.department_id, d.department
HAVING SUM(o.quantity * p.unit_price) > 15000000
ORDER BY total_revenue DESC;

--4.Is it true that customers buy more alcoholic products on Christmas Day 2019?
WITH daily_alcohol_sales AS (
    SELECT
        o.order_date,
        SUM(o.quantity) AS quantity_sold
    FROM orders o
    INNER JOIN products p
        ON o.product_id = p.product_id
    INNER JOIN departments d
        ON p.dept_id = d.department_id
    WHERE LOWER(d.department) = 'alcohol'
      AND o.order_date >= DATE '2019-12-01'
      AND o.order_date < DATE '2020-01-01'
    GROUP BY o.order_date
),
christmas_comparison AS (
   SELECT
   COALESCE(
   MAX(quantity_sold) FILTER (
      WHERE order_date = DATE '2019-12-25'
       ), 0
       ) AS christmas_quantity,
  AVG(quantity_sold) AS average_recorded_daily_quantity
  FROM daily_alcohol_sales
)
SELECT
    christmas_quantity,
    ROUND(average_recorded_daily_quantity, 2)
    AS average_recorded_daily_quantity,
    CASE
    WHEN christmas_quantity > average_recorded_daily_quantity
    THEN 'Yes'
    ELSE 'No'
    END AS sold_more_than_december_daily_average
FROM christmas_comparison;

--5.Which year did we generate the most profit?
SELECT
    EXTRACT(YEAR FROM o.order_date) AS Sales_Year,
    SUM(o.quantity * (p.unit_price - p.unit_cost)) AS Total_Profit
FROM orders o
INNER JOIN products p
    ON o.product_id = p.product_id
GROUP BY EXTRACT(YEAR FROM o.order_date)
ORDER BY total_profit DESC
LIMIT 1;

--6.Has the use of card payments increased in Nigeria since 2022?
SELECT
    EXTRACT(YEAR FROM o.order_date) AS sales_year,
    COUNT(*) AS card_order_rows,
    SUM(o.quantity) AS units_purchased
FROM orders o
INNER JOIN customers c
    ON o.customer_id = c.customer_id
WHERE LOWER(o.payment_type) LIKE '%card%'
  AND o.order_date >= DATE '2015-01-01'
  AND o.order_date < DATE '2024-01-01'
  AND c.address ILIKE '%Nigeria%'
GROUP BY EXTRACT(YEAR FROM o.order_date)
ORDER BY sales_year;

